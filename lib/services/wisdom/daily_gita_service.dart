  /// Maps sequential Shloka index (1 to 701) to Chapter and Verse numbers
  static Map<String, int> getChapterAndVerseForShlokaNumber(int shlokaNumber) {
    int remaining = ((shlokaNumber - 1) % 701) + 1;
    for (int ch = 0; ch < chapterVerseCounts.length; ch++) {
      int count = chapterVerseCounts[ch];
      if (remaining <= count) {
        return {'chapter': ch + 1, 'verse': remaining};
      }
      remaining -= count;
    }
    return {'chapter': 1, 'verse': 1};
  }

  /// Calculates device-specific daily progressive shloka number (Day 1 -> Shloka 1, Day 5 -> Shloka 5)
  static Future<int> getDeviceDayShlokaNumber() async {
    try {
      final prefs = await SharedPreferences.getInstance();
      final now = DateTime.now();
      final todayStr =
          '${now.year}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';
      final lastDate = prefs.getString('gita_device_shloka_last_date');
      int currentDay = prefs.getInt('gita_device_shloka_day_number') ?? 0;

      if (currentDay <= 0) {
        currentDay = 1;
        await prefs.setInt('gita_device_shloka_day_number', 1);
        await prefs.setString('gita_device_shloka_last_date', todayStr);
        return 1;
      }

      if (lastDate != todayStr) {
        currentDay = (currentDay % 701) + 1;
        await prefs.setInt('gita_device_shloka_day_number', currentDay);
        await prefs.setString('gita_device_shloka_last_date', todayStr);
        return currentDay;
      }

      return currentDay;
    } catch (e) {
      debugPrint('[DailyBhagavadGitaService] Error reading device day count: $e');
      return 1;
    }
  }

