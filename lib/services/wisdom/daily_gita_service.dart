    try {
      final prefs = await SharedPreferences.getInstance();
      final cachedRaw = prefs.getString(cacheKey);
      if (cachedRaw != null && cachedRaw.isNotEmpty) {
        final decoded = jsonDecode(cachedRaw);
        final cachedVerse = BhagavadGitaVerse.fromJson(decoded);
        // If requested target language meaning is already cached, return
        if (targetLang != null && targetLang != 'en') {
          if (cachedVerse.meaningByLang.containsKey(targetLang) &&
              cachedVerse.meaningByLang[targetLang]!.isNotEmpty) {
            return cachedVerse;
          }
          // Otherwise translate meaning in background and update cache
          final enMeaning = cachedVerse.getMeaning('en');
          if (enMeaning.isNotEmpty) {
            final translated = await SongTranslationService.instance.translate(
              enMeaning,
              targetLang,
            );
            final updatedMeaning = Map<String, String>.from(cachedVerse.meaningByLang);
            updatedMeaning[targetLang] = translated;
            final updatedVerse = cachedVerse.copyWith(meaningByLang: updatedMeaning);
            await prefs.setString(cacheKey, jsonEncode(updatedVerse.toJson()));
            return updatedVerse;
          }
        }
        return cachedVerse;
      }
    } catch (e) {
      debugPrint('[DailyBhagavadGitaService] Cache read error: $e');
    }

    // Curated fallback if internet is offline
    BhagavadGitaVerse fallbackVerse = getInitialVerseForNumber(shlokaNumber);

    try {
      final url = Uri.parse('https://vedicscriptures.github.io/slok/$ch/$v');
      final res = await http.get(
        url,
        headers: {'User-Agent': 'Mozilla/5.0 (Bhakti App)'},
      ).timeout(const Duration(seconds: 4));

      if (res.statusCode == 200) {
        final data = jsonDecode(res.body);
        if (data is Map) {
          final sanskrit = (data['slok'] as String? ?? '').trim();
          final translit = (data['transliteration'] as String? ?? '').trim();

          // English commentary
          String enMeaning = (data['siva']?['et'] as String? ?? '').trim();
          if (enMeaning.isEmpty) enMeaning = (data['adi']?['et'] as String? ?? '').trim();
          if (enMeaning.isEmpty) enMeaning = (data['purohit']?['et'] as String? ?? '').trim();
          if (enMeaning.isEmpty) enMeaning = (data['gambir']?['et'] as String? ?? '').trim();

          // Hindi commentary
          String hiMeaning = (data['tej']?['ht'] as String? ?? '').trim();

          final chName = chapterNames[ch] ?? {
            'en': 'Chapter $ch',
            'kn': 'ಅಧ್ಯಾಯ $ch',
            'te': 'అధ్యాయం $ch',
            'hi': 'अध्याय $ch',
          };

          final Map<String, String> meaningMap = {
            'en': enMeaning,
            if (hiMeaning.isNotEmpty) 'hi': hiMeaning,
          };

          // Translate meaning if user's target language is kn, te, ta, ml
          if (targetLang != null &&
              targetLang != 'en' &&
              targetLang != 'hi' &&
              enMeaning.isNotEmpty) {
            final translated = await SongTranslationService.instance.translate(
              enMeaning,
              targetLang,
            );
            if (translated.isNotEmpty) {
              meaningMap[targetLang] = translated;
            }
          }

          final verse = BhagavadGitaVerse(
            id: 'bg_${ch}_$v',
            chapter: ch,
            verse: v,
            chapterName: chName,
            theme: {
              'en': 'Sacred Shloka $shlokaNumber of 701',
              'kn': 'ಪವಿತ್ರ ಶ್ಲೋಕ $shlokaNumber (೭೦೧ ರಲ್ಲಿ)',
              'te': 'పవిత్ర శ్లోకం $shlokaNumber (701 లో)',
              'hi': 'पावन श्लोक $shlokaNumber (701 में)',
              'ta': 'புனித சுலோகம் $shlokaNumber',
              'ml': 'വിശുദ്ധ ശ്ലോകം $shlokaNumber',
            },
            sanskrit: sanskrit,
            verseByLang: {
              'sa': sanskrit,
              'en': translit.isNotEmpty ? translit : sanskrit,
            },
            meaningByLang: meaningMap,
          );

          // Persist to SharedPreferences
          try {
            final prefs = await SharedPreferences.getInstance();
            await prefs.setString(cacheKey, jsonEncode(verse.toJson()));
          } catch (_) {}

          return verse;
        }
      }
    } catch (e) {
      debugPrint('[DailyBhagavadGitaService] Internet fetch failed for $ch/$v: $e');
    }

    return fallbackVerse;
  }

  /// Returns today's dynamic Bhagavad Gita Shloka rotated predictably each day of the year
  static BhagavadGitaVerse getTodayGitaShloka([DateTime? date]) {
    final targetDate = date ?? DateTime.now();
    final startOfYear = DateTime(targetDate.year, 1, 1);
    final dayIndex = targetDate.difference(startOfYear).inDays;
    return _gitaVerses[dayIndex.abs() % _gitaVerses.length];
  }

  static BhagavadGitaVerse getVerseById(String id) {
    return _gitaVerses.firstWhere(
      (v) => v.id == id,
      orElse: () => _gitaVerses.first,
    );
  }
