/// Model representing a Sacred Bhagavad Gita Shloka with authentic multi-language support.
class BhagavadGitaVerse {
  final String id;
  final int chapter;
  final int verse;
  final Map<String, String> chapterName;
  final Map<String, String> theme;
  final String sanskrit;
  final Map<String, String> verseByLang;
  final Map<String, String> meaningByLang;

  const BhagavadGitaVerse({
    required this.id,
    required this.chapter,
    required this.verse,
    required this.chapterName,
    required this.theme,
    required this.sanskrit,
    required this.verseByLang,
    required this.meaningByLang,
  });

  Map<String, dynamic> toJson() => {
        'id': id,
        'chapter': chapter,
        'verse': verse,
        'chapterName': chapterName,
        'theme': theme,
        'sanskrit': sanskrit,
        'verseByLang': verseByLang,
        'meaningByLang': meaningByLang,
      };

  factory BhagavadGitaVerse.fromJson(Map<String, dynamic> json) => BhagavadGitaVerse(
        id: json['id'] as String? ?? 'bg_${json['chapter']}_${json['verse']}',
        chapter: (json['chapter'] as num?)?.toInt() ?? 1,
        verse: (json['verse'] as num?)?.toInt() ?? 1,
        chapterName: Map<String, String>.from((json['chapterName'] as Map?) ?? {}),
        theme: Map<String, String>.from((json['theme'] as Map?) ?? {}),
        sanskrit: json['sanskrit'] as String? ?? '',
        verseByLang: Map<String, String>.from((json['verseByLang'] as Map?) ?? {}),
        meaningByLang: Map<String, String>.from((json['meaningByLang'] as Map?) ?? {}),
      );

  BhagavadGitaVerse copyWith({
    Map<String, String>? meaningByLang,
    Map<String, String>? verseByLang,
  }) {
    return BhagavadGitaVerse(
      id: id,
      chapter: chapter,
      verse: verse,
      chapterName: chapterName,
      theme: theme,
      sanskrit: sanskrit,
      verseByLang: verseByLang ?? this.verseByLang,
      meaningByLang: meaningByLang ?? this.meaningByLang,
    );
  }

  String getChapterName(String lang) {
    return chapterName[lang] ?? chapterName['en'] ?? 'Bhagavad Gita';
  }

  String getTheme(String lang) {
    return theme[lang] ?? theme['en'] ?? 'Divine Wisdom';
  }

  String getVerse(String lang) {
    return verseByLang[lang] ?? verseByLang['kn'] ?? verseByLang['sa'] ?? sanskrit;
  }

  String getMeaning(String lang) {
    return meaningByLang[lang] ?? meaningByLang['kn'] ?? meaningByLang['en'] ?? '';
  }

  String getReference(String lang) {
    switch (lang) {
      case 'kn':
        return 'ಅಧ್ಯಾಯ $chapter • ಶ್ಲೋಕ $verse';
      case 'te':
        return 'అధ్యాయం $chapter • శ్లోకం $verse';
      case 'hi':
        return 'अध्याय $chapter • श्लोक $verse';
      case 'ta':
        return 'அத்தியாயம் $chapter • சுலோகம் $verse';
      case 'ml':
        return 'അധ്യായം $chapter • ശ്ലോകം $verse';
      case 'en':
      default:
        return 'Chapter $chapter • Verse $verse';
    }
  }
}

